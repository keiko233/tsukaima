/**
 * Better Auth owns these four tables. They intentionally use `auth_` names so the domain `users`
 * table and the authentication principal never get confused in queries or migrations.
 *
 * The adapter receives `authSchema` with Better Auth model names (`user`, `session`, ...), while
 * the physical SQLite table names stay `auth_*`. Dates use `timestamp_ms`, matching the schema
 * generated by Better Auth 1.7 for SQLite.
 */
export const authUser = sqliteTable("auth_user", {
	createdAt: integer("created_at", { mode: "timestamp_ms" })
		.notNull()
		.default(sql`(cast(unixepoch('subsecond') * 1000 as integer))`),
	displayUsername: text("display_username"),
	email: text("email").notNull().unique(),
	emailVerified: integer("email_verified", { mode: "boolean" }).notNull().default(false),
	id: text("id").primaryKey(),
	image: text("image"),
	name: text("name").notNull(),
	updatedAt: integer("updated_at", { mode: "timestamp_ms" })
		.notNull()
		.$onUpdate(() => new Date()),
	username: text("username").unique(),
});

