import { createORPCClient } from "@orpc/client";
import { RPCLink } from "@orpc/client/fetch";
import type { ContractRouterClient } from "@orpc/contract";
import { createTanstackQueryUtils } from "@orpc/tanstack-query";
import type { AppContract } from "@tsukaima/contracts";

/**
 * The WebUI talks to the server exclusively through the oRPC contract in `@tsukaima/contracts`.
 * Types are never declared here: they are re-exported from the contract, and the client/router
 * utilities are inferred from it, so the wire surface stays in lockstep with the server.
 */
export type {
	AuthStatus,
	ChatSummary,
	ConversationRow,
	DeliveryStatus,
	DiagnosticsData,
	GroupDetail,
	GroupSummary,
	LogEntry,
	LogLevel,
	LogSnapshot,
	MessageSummary,
	ModelPolicy,
	ModelPolicyRow,
	PluginRow,
	RemoteModelList,
	RequestRow,
	SessionDetail,
	SessionSummary,
	SettingsView,
	UserDetail,
	UserSummary,
} from "@tsukaima/contracts";

const RPC_URL = import.meta.env.VITE_RPC_URL ?? "/rpc";

export const client: ContractRouterClient<AppContract> = createORPCClient(
	new RPCLink({
		url: RPC_URL,
		// The admin session cookie is the only credential; make sure it rides along on same-origin
		// calls even when the browser default would differ.
		fetch: (request, init) => fetch(request, { ...init, credentials: "same-origin" }),
	}),
);

/**
 * TanStack Query integration. Prefer `orpc.<router>.<procedure>.queryOptions()/mutationOptions()`
 * so query keys and mutation lifecycles are generated by the contract rather than by hand.
 */
export const orpc = createTanstackQueryUtils(client);
